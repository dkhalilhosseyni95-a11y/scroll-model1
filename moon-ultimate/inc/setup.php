/**
 * Register theme supports, menus and image sizes.
 */
function moon_setup() {
	load_theme_textdomain( 'moon-theme', MOON_THEME_DIR . '/languages' );

	add_theme_support( 'automatic-feed-links' );
	add_theme_support( 'title-tag' );
	add_theme_support( 'post-thumbnails' );
	add_theme_support( 'html5', array( 'search-form', 'comment-form', 'comment-list', 'gallery', 'caption', 'style', 'script' ) );
	add_theme_support( 'custom-logo', array(
		'height'      => 120,
		'width'       => 320,
		'flex-height' => true,
		'flex-width'  => true,
	) );
	add_theme_support( 'customize-selective-refresh-widgets' );
	add_theme_support( 'align-wide' );
	add_theme_support( 'responsive-embeds' );
	add_theme_support( 'editor-styles' );

	add_image_size( 'moon-card', 900, 1200, true );
	add_image_size( 'moon-wide', 1920, 1088, true );
	add_image_size( 'moon-thumb', 240, 320, true );

	register_nav_menus( array(
		'primary' => __( 'منوی اصلی', 'moon-theme' ),
		'footer'  => __( 'منوی فوتر', 'moon-theme' ),
	) );
}
add_action( 'after_setup_theme', 'moon_setup' );

/**
 * Content width used by embeds and wide blocks.
 */
function moon_content_width() {
	$GLOBALS['content_width'] = apply_filters( 'moon_content_width', 800 );
}
add_action( 'after_setup_theme', 'moon_content_width', 0 );

/**
 * Register widget areas. WooCommerce filters live in the shop sidebar.
 */
function moon_widgets_init() {
	register_sidebar( array(
		'name'          => __( 'فیلتر فروشگاه', 'moon-theme' ),
		'id'            => 'shop-sidebar',
		'description'   => __( 'ویجت‌های فیلتر محصولات (ووکامرس).', 'moon-theme' ),
		'before_widget' => '<section id="%1$s" class="moon-widget %2$s">',
		'after_widget'  => '</section>',
		'before_title'  => '<h2 class="moon-widget__title">',
		'after_title'   => '</h2>',
	) );

	register_sidebar( array(
		'name'          => __( 'نوار کناری وبلاگ', 'moon-theme' ),
		'id'            => 'blog-sidebar',
		'before_widget' => '<section id="%1$s" class="moon-widget %2$s">',
		'after_widget'  => '</section>',
		'before_title'  => '<h2 class="moon-widget__title">',
		'after_title'   => '</h2>',
	) );
}
add_action( 'widgets_init', 'moon_widgets_init' );

/**
 * Body classes for the theme, layout direction and active page context.
 *
 * @param array $classes Existing classes.
 * @return array
 */
function moon_body_classes( $classes ) {
	$classes[] = 'moon-body';

	if ( is_front_page() ) {
		$classes[] = 'moon-front';
	}

	if ( is_singular() ) {
		$classes[] = 'moon-singular';
	}

	if ( ! is_active_sidebar( 'shop-sidebar' ) ) {
		$classes[] = 'moon-no-shop-filters';
	}

	return $classes;
}
add_filter( 'body_class', 'moon_body_classes' );

/**
 * Add a pingback header on singular pages.
 */
function moon_pingback_header() {
	if ( is_singular() && pings_open() ) {
		printf( '<link rel="pingback" href="%s">', esc_url( get_bloginfo( 'pingback_url' ) ) );
	}
}
add_action( 'wp_head', 'moon_pingback_header' );

/**
 * Apply brand settings (accent colour, display font, type scale and the mobile
 * overrides) as CSS custom properties.
 */
function moon_brand_css() {
	$css = '';

	// Colours, fonts and the type scale are generated by Moon_Tokens from the
	// panel's design pages; this function only carries the mobile rules.

	$hero_height = (int) moon_opt( 'hero_mobile_min_height', 640 );

	if ( $hero_height && 640 !== $hero_height ) {
		$css .= '@media (max-width:767px){.moon-hero{min-height:' . max( 420, min( 900, $hero_height ) ) . 'px;}}';
	}

	if ( moon_opt( 'mobile_hide_scrollstory' ) ) {
		$css .= '@media (max-width:767px){.moon-scrollstory{display:none;}}';
	}

	if ( $css ) {
		wp_add_inline_style( 'moon-base', $css );
	}
}
add_action( 'wp_enqueue_scripts', 'moon_brand_css', 20 );

/**
 * The design is right-to-left Persian: keep dir/lang correct even if the
 * site language was left on English during setup.
 *
 * @param string $output Existing attributes.
 * @return string
 */
function moon_language_attributes( $output ) {
	if ( false === strpos( $output, 'dir=' ) ) {
		$output .= ' dir="rtl"';
	}

	return $output;
}
add_filter( 'language_attributes', 'moon_language_attributes' );

/**
 * jquery-migrate is not needed by the theme or current WooCommerce; drop the extra request.
 *
 * @param WP_Scripts $scripts Scripts registry.
 */
function moon_drop_jquery_migrate( $scripts ) {
	if ( ! is_admin() && isset( $scripts->registered['jquery'] ) ) {
		$scripts->registered['jquery']->deps = array_diff( $scripts->registered['jquery']->deps, array( 'jquery-migrate' ) );
	}
}
add_action( 'wp_default_scripts', 'moon_drop_jquery_migrate' );
