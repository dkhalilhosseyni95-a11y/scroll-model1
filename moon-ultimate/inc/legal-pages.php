/**
 * Replace tokens when a legal page is displayed.
 *
 * @param string $content Content.
 * @return string
 */
function moon_legal_render_tokens( $content ) {
	if ( ! is_singular( 'page' ) || ! get_post_meta( get_the_ID(), '_moon_legal', true ) ) {
		return $content;
	}

	$bits = array();

	if ( moon_opt( 'contact_email' ) ) {
		/* translators: %s: email address. */
		$bits[] = sprintf( __( 'ایمیل: %s', 'moon-theme' ), '<span dir="ltr">' . esc_html( moon_opt( 'contact_email' ) ) . '</span>' );
	}

	if ( moon_opt( 'contact_phone' ) ) {
		/* translators: %s: phone number. */
		$bits[] = sprintf( __( 'تلفن: %s', 'moon-theme' ), '<span dir="ltr">' . esc_html( moon_opt( 'contact_phone' ) ) . '</span>' );
	}

	$contact = $bits ? ' ' . implode( ' | ', $bits ) : '';

	return strtr( $content, array(
		'{store}'   => esc_html( moon_brand_text() ),
		'{site}'    => esc_html( wp_parse_url( home_url(), PHP_URL_HOST ) ),
		'{contact}' => $contact,
	) );
}
add_filter( 'the_content', 'moon_legal_render_tokens', 9 );

/**
 * Create the pages once; never overwrite content the owner has written.
 */
function moon_legal_setup() {
	if ( get_option( 'moon_legal_version' ) === MOON_LEGAL_VERSION ) {
		return;
	}

	$pages = array(
		'terms'    => array( 'قوانین و مقررات', array() ),
		'privacy'  => array( 'حریم خصوصی', array( '', '<p>اطلاعات ثبت‌شده فقط برای پردازش سفارش و پشتیبانی استفاده می‌شود.</p>' ) ),
		'shipping' => array( 'ارسال و بازگشت', array( '', '<p>شرایط ارسال و مرجوعی کالا را اینجا بنویسید.</p>' ) ),
	);

	foreach ( $pages as $slug => $def ) {
		$existing = get_page_by_path( $slug );
		$content  = moon_legal_default( $slug );

		if ( ! $existing ) {
			$id = wp_insert_post( array(
				'post_title'   => $def[0],
				'post_name'    => $slug,
				'post_content' => $content,
				'post_status'  => 'publish',
				'post_type'    => 'page',
			) );
		} else {
			$id = $existing->ID;

			// Only replace the factory placeholder; anything else was written by the owner.
			if ( ! in_array( trim( (string) $existing->post_content ), array_map( 'trim', $def[1] ), true ) ) {
				$id = 0;
			} else {
				wp_update_post( array( 'ID' => $id, 'post_content' => $content ) );
			}
		}

		if ( $id && ! is_wp_error( $id ) ) {
			update_post_meta( $id, '_moon_legal', '1' );
			update_post_meta( $id, '_wp_page_template', 'page-legal.php' );
		}
	}

	update_option( 'moon_legal_version', MOON_LEGAL_VERSION, false );
}
add_action( 'init', 'moon_legal_setup', 30 );

/**
 * Table of contents from <h2> headings; adds ids to them.
 *
 * @param string $html Rendered content.
 * @return array{0:string,1:string} Toc html, content html.
 */
function moon_legal_toc( $html ) {
	$items = array();
	$n     = 0;

	$html = preg_replace_callback( '#<h2([^>]*)>(.*?)</h2>#su', function ( $m ) use ( &$items, &$n ) {
		$n++;
		$id      = 'sec-' . $n;
		$items[] = '<li><a href="#' . $id . '">' . wp_strip_all_tags( $m[2] ) . '</a></li>';

		return '<h2' . $m[1] . ' id="' . $id . '">' . $m[2] . '</h2>';
	}, $html );

	return array( $items ? '<ol>' . implode( '', $items ) . '</ol>' : '', $html );
}
