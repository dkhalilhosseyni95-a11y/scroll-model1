/**
 * Starter content of a legal page as editor-ready HTML.
 *
 * @param string $kind privacy|terms.
 * @return string
 */
function moon_legal_content_html( $kind = 'privacy' ) {
	$html = '';

	foreach ( moon_legal_sections( $kind ) as $index => $section ) {
		$html .= '<h2>' . esc_html( $section['title'] ) . '</h2>';

		foreach ( $section['body'] as $paragraph ) {
			$html .= '<p>' . esc_html( $paragraph ) . '</p>';
		}
	}

	return $html;
}
